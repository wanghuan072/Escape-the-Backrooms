import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const locales = ['en', 'de', 'fr', 'es']
const sections = [
  ['levels', 'levels'],
  ['maps', 'maps-keys'],
]

const addPrefix = (routePath, locale) => (locale === 'en' ? routePath : `/${locale}${routePath}`)
const routeMap = {}

for (const [dataDirectory, routeSection] of sections) {
  const datasets = {}
  for (const locale of locales) {
    datasets[locale] = (await import(`../../src/content/${dataDirectory}/${locale}.js`)).default
  }

  for (const sourceLocale of locales) {
    for (const sourceEntry of datasets[sourceLocale]) {
      const sourcePath = addPrefix(`/${routeSection}/${sourceEntry.addressBar}`, sourceLocale)
      routeMap[sourcePath] = Object.fromEntries(
        locales.map((targetLocale) => {
          const targetEntry = datasets[targetLocale].find((entry) => entry.id === sourceEntry.id)
          return [targetLocale, addPrefix(`/${routeSection}/${targetEntry.addressBar}`, targetLocale)]
        }),
      )
    }
  }
}

const gamesModule = await import('../../src/content/related-games.js')
for (const sourceLocale of locales) {
  const sourceGames = gamesModule.getRelatedGames(sourceLocale)
  for (const sourceGame of sourceGames) {
    const sourcePath = addPrefix(`/backrooms-games/${sourceGame.addressBar}`, sourceLocale)
    routeMap[sourcePath] = Object.fromEntries(
      locales.map((targetLocale) => {
        const targetGame = gamesModule
          .getRelatedGames(targetLocale)
          .find((game) => game.id === sourceGame.id)
        return [targetLocale, addPrefix(`/backrooms-games/${targetGame.addressBar}`, targetLocale)]
      }),
    )
  }
}

const target = path.join(rootDir, 'src/config/localized-routes.generated.ts')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(
  target,
  `// Generated by scripts/data/generate-localized-routes.js. Do not edit directly.\nimport type { Locale } from '@/types/locale'\n\nexport const localizedRouteMap = ${JSON.stringify(routeMap, null, 2)} as Record<string, Record<Locale, string>>\n`,
  'utf8',
)

console.log(`Generated ${Object.keys(routeMap).length} localized detail-route mappings.`)
