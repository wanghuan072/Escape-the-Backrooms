import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const imageRoot = path.join(rootDir, 'public', 'images')
const outputPath = path.join(rootDir, 'src', 'config', 'image-dimensions.generated.ts')

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name)
    return entry.isDirectory() ? walk(target) : [target]
  })
}

const dimensions = {}
for (const filePath of walk(imageRoot).sort()) {
  const metadata = await sharp(filePath).metadata()
  if (!metadata.width || !metadata.height) continue
  const publicPath = `/${path.relative(path.join(rootDir, 'public'), filePath).replaceAll('\\', '/')}`
  dimensions[publicPath] = { width: metadata.width, height: metadata.height }
}

const source = `// Generated by scripts/data/generate-image-dimensions.js.\n` +
  `export const imageDimensions: Readonly<Record<string, Readonly<{ width: number; height: number }>>> = ${JSON.stringify(dimensions, null, 2)}\n`

fs.writeFileSync(outputPath, source)
console.log(`Generated intrinsic dimensions for ${Object.keys(dimensions).length} images.`)
